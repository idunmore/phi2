#!/usr/bin/env python3
"""Generates clock_fonts.h: subsets of the u8g2 fonts, holding only the glyphs
that nano-clock-oled draws.  Glyph data is copied byte for byte, so what is drawn
is pixel-identical to the original fonts.

A character missing from the subset is silently NOT drawn, so whenever the sketch
gains new text or icons, update TEXT or ICONS below, then re-run this script:

    python3 subset_fonts.py [path/to/u8g2_fonts.c]

The default path is the standard Arduino library location on macOS and Linux.
"""
import re
import sys
from pathlib import Path

# Code points of every icon the sketch draws (the *_GLYPH defines)
ICONS = {0x7b, 0xd9, 0xd3, 0xee, 0xf3, 0x81, 0x78, 0x79, 0xb7}

# Every string the sketch draws in the large font
TEXT = [
    # Frequencies
    "1", "2", "4", "5", "8", "10", "25", "50", "100", "250", "500",
    # Bands
    "Hz", "kHz", "MHz",
    # Status messages
    "Step", "Run", "Stop", "Clock", "Reset", "Save", "RstON", "RstOFF",
]

ICON_FONT = "u8g2_font_open_iconic_all_2x_t"
TEXT_FONT = "u8g2_font_calblk36_tr"

DEFAULT_FONTS_C = Path.home() / "Documents/Arduino/libraries/U8g2/src/clib/u8g2_fonts.c"
OUTPUT = Path(__file__).resolve().parent.parent / "clock_fonts.h"

HEADER_SIZE = 23  # u8g2 font header; glyph records follow it
SIMPLE_ESCAPES = {"n": 10, "t": 9, "r": 13, '"': 34, "\\": 92, "'": 39, "?": 63,
                  "a": 7, "b": 8, "f": 12, "v": 11}

BYTES_PER_ROW = 16

def load_font(source, name):
    """Returns the bytes of a font, parsed from its C string literal."""
    match = re.search(
        r"const uint8_t " + name + r"\[(\d+)\] U8G2_FONT_SECTION\(\"" + name
        + r"\"\)\s*=\s*((?:\"(?:[^\"\\]|\\.)*\"\s*)+);", source, re.S)
    if not match:
        sys.exit(f"Font not found: {name}")

    data = bytearray()
    for literal in re.findall(r'"((?:[^"\\]|\\.)*)"', match.group(2)):
        i = 0
        while i < len(literal):
            if literal[i] != "\\":
                data.append(ord(literal[i]))
                i += 1
                continue
            octal = re.match(r"[0-7]{1,3}", literal[i + 1:])
            if octal:
                data.append(int(octal.group(), 8))
                i += 1 + len(octal.group())
            else:
                data.append(SIMPLE_ESCAPES[literal[i + 1]])
                i += 2
    data.append(0)  # The string literal's implicit NUL terminator

    if len(data) != int(match.group(1)):
        sys.exit(f"{name}: parsed {len(data)} bytes, expected {match.group(1)}")
    return bytes(data)


def glyph_records(font):
    """Returns (encoding, record bytes) for each glyph in the 8-bit glyph list."""
    records, pos = [], HEADER_SIZE
    while font[pos + 1] != 0:  # Each record is: encoding, length to next, data
        records.append((font[pos], font[pos:pos + font[pos + 1]]))
        pos += font[pos + 1]
    return records


def subset_font(font, name, encodings):
    """Returns a copy of the font that contains only the given encodings."""
    records = [r for r in glyph_records(font) if r[0] in encodings]
    missing = encodings - {encoding for encoding, _ in records}
    if missing:
        sys.exit(f"{name} has no glyph for: {sorted(missing)}")

    # Lookups start from these offsets, based on the encoding being searched for
    upper_a = lower_a = None
    body = bytearray()
    for encoding, record in records:
        if upper_a is None and encoding >= ord("A"):
            upper_a = len(body)
        if lower_a is None and encoding >= ord("a"):
            lower_a = len(body)
        body += record

    end = len(body)
    body += b"\0\0"  # End of the 8-bit glyph list
    unicode_table = len(body)
    body += b"\0\0\0\4\xff\xff\0"  # Empty unicode lookup table

    header = bytearray(font[:HEADER_SIZE])
    header[0] = len(records)
    header[17:19] = (end if upper_a is None else upper_a).to_bytes(2, "big")
    header[19:21] = (end if lower_a is None else lower_a).to_bytes(2, "big")
    header[21:23] = unicode_table.to_bytes(2, "big")
    return bytes(header + body)


def c_array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + BYTES_PER_ROW])
                for i in range(0, len(data), BYTES_PER_ROW)]
    return (f"const uint8_t {name}[{len(data)}] U8X8_PROGMEM = {{\n  "
            + ",\n  ".join(rows) + "\n};\n")


def main():
    fonts_c = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_FONTS_C
    source = fonts_c.read_text(encoding="latin-1")

    icon_font = load_font(source, ICON_FONT)
    text_font = load_font(source, TEXT_FONT)
    icon_subset = subset_font(icon_font, ICON_FONT, ICONS)
    text_subset = subset_font(text_font, TEXT_FONT, {ord(c) for s in TEXT for c in s})

    OUTPUT.write_text(
        "// Generated by ./tools/subset_fonts.py - do not edit.\n"
        "// Subsets of u8g2 fonts, containing only the glyphs this sketch draws.\n"
        f"// Glyph data is copied verbatim from {ICON_FONT} and {TEXT_FONT}.\n"
        "#pragma once\n#include <U8g2lib.h>\n\n"
        + c_array("clock_icon_font", icon_subset) + "\n"
        + c_array("clock_text_font", text_subset))

    print(f"{ICON_FONT}: {len(icon_font)} -> {len(icon_subset)} bytes")
    print(f"{TEXT_FONT}: {len(text_font)} -> {len(text_subset)} bytes")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
